const assert = require("node:assert/strict");
const { join } = require("node:path");

module.exports = async ({ page, url, request, prisma, evidence }) => {
  const { expect } = require("../frontend/node_modules/playwright/test");
  const supplier = await request("/api/suppliers", "POST", { name: "Proveedor de ingresos desde Stock", phone: "789", email: "" });
  await page.goto(url + "/productos");
  await page.getByRole("button", { name: "Nuevo producto", exact: true }).click();
  let dialog = page.getByRole("dialog");
  assert.equal(await dialog.getByText("Stock inicial", { exact: true }).count(), 0, "New product must not allow initial stock");
  await dialog.getByPlaceholder("Nombre del producto", { exact: true }).fill("Producto sin stock inicial QA");
  const createdResponse = page.waitForResponse(response => response.url().endsWith("/api/products") && response.request().method() === "POST");
  await dialog.getByRole("button", { name: "Guardar producto", exact: true }).click();
  const product = await (await createdResponse).json();
  assert.equal(product.physicalStock, 0);
  await expect(dialog).toHaveCount(0);
  async function inventory() { return (await request("/api/stock")).find(row => row.productId === product.id); }
  async function openIncrease() {
    await page.goto(url + "/stock");
    await page.getByRole("row").filter({ hasText: product.name }).getByRole("button", { name: "Acciones", exact: true }).click();
    await expect(page.getByRole("menuitem", { name: "Clasificar", exact: true })).toHaveCount(0);
    await page.getByRole("menuitem", { name: "Aumentar stock", exact: true }).click();
    dialog = page.getByRole("dialog");
    await expect(dialog.getByRole("heading", { name: "Aumentar stock", exact: true })).toBeVisible();
  }
  async function select(label, value) {
    await dialog.getByRole("combobox", { name: label, exact: true }).click();
    await page.getByRole("option", { name: value, exact: true }).click();
  }
  await openIncrease();
  await select("Proveedor", supplier.name);
  await dialog.getByLabel("Unidades a ingresar", { exact: true }).fill("4");
  await dialog.getByLabel("Costo por unidad", { exact: true }).fill("100,01");
  await select("Condición de pago", "A crédito");
  await expect(dialog.getByRole("button", { name: "Registrar compra", exact: true })).toBeDisabled();
  await dialog.getByLabel("Vencimiento del pago", { exact: true }).fill("2026-12-31");
  assert.equal((await inventory()).physicalStock, 0, "Filling the modal must not add stock");
  await page.screenshot({ path: join(evidence, "stock-ingreso-credito.png"), fullPage: true, animations: "disabled" });
  await dialog.screenshot({ path: join(evidence, "stock-ingreso-credito-dialog.png"), animations: "disabled" });
  await page.route("**/api/purchases", async route => { await route.fetch(); await route.abort("failed"); }, { times: 1 });
  await dialog.getByRole("button", { name: "Registrar compra", exact: true }).click();
  await expect(dialog.getByRole("alert")).toBeVisible();
  await dialog.getByRole("button", { name: "Registrar compra", exact: true }).click();
  await expect(dialog).toHaveCount(0);
  assert.equal(await prisma.purchase.count({ where: { supplierId: supplier.id } }), 1, "Retry must not duplicate the purchase");
  assert.equal((await inventory()).physicalStock, 4);
  assert.equal((await inventory()).creditQty, 4);
  assert.equal((await inventory()).unclassifiedQty, 0);
  assert.equal((await request(`/api/supplier-payables/account/${supplier.id}`)).balanceCents, 40004);
  await page.goto(url + "/compras");
  await expect(page.getByRole("row").filter({ hasText: `4× ${product.name}` })).toBeVisible();
  await openIncrease();
  await select("Proveedor", supplier.name);
  await dialog.getByLabel("Unidades a ingresar", { exact: true }).fill("2");
  await dialog.getByLabel("Costo por unidad", { exact: true }).fill("100,01");
  await select("Condición de pago", "Pagada");
  await page.setViewportSize({ width: 390, height: 844 });
  await dialog.getByRole("button", { name: "Registrar compra", exact: true }).scrollIntoViewIfNeeded();
  await expect(dialog.getByRole("button", { name: "Registrar compra", exact: true })).toBeInViewport();
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await dialog.screenshot({ path: join(evidence, "stock-ingreso-pagado-mobile.png"), animations: "disabled" });
  await dialog.getByRole("button", { name: "Registrar compra", exact: true }).click();
  await expect(dialog).toHaveCount(0);
  await page.setViewportSize({ width: 1280, height: 800 });
  assert.equal((await inventory()).physicalStock, 6);
  assert.equal((await inventory()).paidQty, 2);
  assert.equal((await inventory()).creditQty, 4);
  assert.equal((await inventory()).unclassifiedQty, 0);
  assert.equal((await request(`/api/supplier-payables/account/${supplier.id}`)).balanceCents, 40004);
  await page.goto(url + "/stock");
  const row = page.getByRole("row").filter({ hasText: product.name });
  await row.getByRole("button", { name: "Acciones", exact: true }).click();
  await page.getByRole("menuitem", { name: "Ajustar stock", exact: true }).click();
  dialog = page.getByRole("dialog");
  await select("Tipo de ajuste", "Conteo físico");
  await dialog.getByLabel("Stock contado", { exact: true }).fill("8");
  await expect(dialog.getByRole("button", { name: "Guardar ajuste", exact: true })).toBeDisabled();
  await dialog.getByRole("button", { name: "Registrar ingreso de 2 unidades", exact: true }).click();
  await expect(dialog.getByRole("heading", { name: "Aumentar stock", exact: true })).toBeVisible();
  await expect(dialog.getByLabel("Unidades a ingresar", { exact: true })).toHaveValue("2");
  await dialog.getByRole("button", { name: "Cancelar", exact: true }).click();
  assert.equal((await inventory()).physicalStock, 6);
  await row.getByRole("button", { name: "Acciones", exact: true }).click();
  await page.getByRole("menuitem", { name: "Ajustar stock", exact: true }).click();
  dialog = page.getByRole("dialog");
  await dialog.getByLabel("Cantidad", { exact: true }).fill("1");
  await dialog.getByRole("button", { name: "Guardar ajuste", exact: true }).click();
  await expect(dialog).toHaveCount(0);
  assert.equal((await inventory()).physicalStock, 5);
  assert.equal((await inventory()).unclassifiedQty, 0);
  await row.getByRole("button", { name: "Acciones", exact: true }).click();
  await page.getByRole("menuitem", { name: "Ajustar stock", exact: true }).click();
  dialog = page.getByRole("dialog");
  await select("Tipo de ajuste", "Conteo físico");
  await dialog.getByLabel("Stock contado", { exact: true }).fill("0");
  await dialog.getByRole("button", { name: "Guardar ajuste", exact: true }).click();
  await expect(dialog).toHaveCount(0);
  assert.equal((await inventory()).physicalStock, 0);
  assert.equal((await inventory()).unclassifiedQty, 0);
  assert.equal(await prisma.purchase.count({ where: { supplierId: supplier.id } }), 2, "Corrections must not create additional purchases");
  assert.equal((await request(`/api/supplier-payables/account/${supplier.id}`)).balanceCents, 40004, "A stock count must not pay supplier debt");
  return { catalogZeroStock: true, purchaseFromStock: true, paidAndCredit: true, retryWithoutDuplicates: true, positiveCountRequiresPurchase: true };
};
